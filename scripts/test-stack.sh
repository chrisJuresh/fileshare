#!/usr/bin/env bash
# Local end-to-end test stack: the REAL app (node dist/main.js) on loopback test ports, the restic
# runner (production image + mounts, this checkout's dist/), real Syncthing ("server" + a stand-in
# "pc", paired with scripts/pair-pc.sh) and a local JWKS standing in for Cloudflare Access.
# Synthetic data and throwaway secrets only; everything lives under $STACK_DIR.
#
#   scripts/test-stack.sh start [--syncthing real|fake] [--no-restic]
#   scripts/test-stack.sh stop [--clean]       stop everything (--clean also deletes $STACK_DIR)
#   scripts/test-stack.sh restic start|stop    start/stop only the restic runner
#   scripts/test-stack.sh status
#
# Environment: FILESHARE_SCRATCH (default /srv/fileshare-scratch), STACK_DIR
# (default $FILESHARE_SCRATCH/stack), FILESHARE_TEST_IMAGE (default fileshare:dev; built as
# fileshare-test:local if missing), ports TS_PUBLIC_PORT (18090) TS_ADMIN_PORT (18091)
# TS_JWKS_PORT (18092) TS_BT_PORT (18890) TS_WEBRTC_PORT (18891) TS_ST_SERVER_PORT (18384)
# TS_ST_PC_PORT (18385), INGEST_QUIET_SECONDS (15).
# Tests read $STACK_DIR/stack.json. Docker objects use the compose project `fileshare-test`.
set -euo pipefail
# shellcheck source=scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SCRATCH=${FILESHARE_SCRATCH:-/srv/fileshare-scratch}
STACK_DIR=${STACK_DIR:-$SCRATCH/stack}
PROJECT=fileshare-test
COMPOSE_FILE_TEST="$REPO_DIR/compose.test.yaml"
PUBLIC_PORT=${TS_PUBLIC_PORT:-18090}
ADMIN_PORT=${TS_ADMIN_PORT:-18091}
JWKS_PORT=${TS_JWKS_PORT:-18092}
BT_PORT=${TS_BT_PORT:-18890}
WEBRTC_PORT=${TS_WEBRTC_PORT:-18891}
ST_SERVER_PORT=${TS_ST_SERVER_PORT:-18384}
ST_PC_PORT=${TS_ST_PC_PORT:-18385}
QUIET=${INGEST_QUIET_SECONDS:-15}
FOLDER_ID=fileshare-outbox
IMAGE=${FILESHARE_TEST_IMAGE:-fileshare:dev}
RUN="$STACK_DIR/run"
LOGS="$STACK_DIR/logs"
APP_ENV="$STACK_DIR/stack.env"
COMPOSE_ENV="$STACK_DIR/compose.env"

usage() {
  sed -n '2,17p' "$0"
  exit "${1:-0}"
}

compose() { docker compose -p "$PROJECT" -f "$COMPOSE_FILE_TEST" --env-file "$COMPOSE_ENV" "$@"; }

# Guard for anything that deletes: STACK_DIR must look like ours.
check_stack_dir() {
  [[ $STACK_DIR == /* && $STACK_DIR == *fileshare* && $STACK_DIR != *..* ]] || die "refusing STACK_DIR=$STACK_DIR"
}

port_free() { ! ss -Htlnu | awk '{print $5}' | grep -qE "[:.]$1\$"; }

pid_alive() { [[ -f $RUN/$1.pid ]] && kill -0 "$(cat "$RUN/$1.pid")" 2>/dev/null; }

# start_bg NAME CMD... — run CMD detached with a clean environment plus $APP_ENV, log to $LOGS/NAME.log
start_bg() {
  local name=$1
  shift
  local envs=()
  mapfile -t envs < <(grep -E '^[A-Z_][A-Z0-9_]*=' "$APP_ENV")
  (
    cd "$REPO_DIR"
    exec env -i PATH="$PATH" HOME="$HOME" TMPDIR="$STACK_DIR/tmp" "${envs[@]}" "$@" >>"$LOGS/$name.log" 2>&1
  ) &
  echo $! >"$RUN/$name.pid"
}

stop_pid() {
  local name=$1 pid i
  [[ -f $RUN/$name.pid ]] || return 0
  pid=$(cat "$RUN/$name.pid")
  if kill -0 "$pid" 2>/dev/null; then
    kill -TERM "$pid" 2>/dev/null || true
    for i in $(seq 1 100); do
      kill -0 "$pid" 2>/dev/null || break
      sleep 0.2
    done
    kill -0 "$pid" 2>/dev/null && kill -KILL "$pid" 2>/dev/null || true
    info "stopped $name"
  fi
  rm -f "$RUN/$name.pid"
}

wait_http() { # URL SECONDS
  local i
  for i in $(seq 1 "$(($2 * 4))"); do
    curl -fsS -m 2 -o /dev/null "$1" 2>/dev/null && return 0
    sleep 0.25
  done
  return 1
}

# st PORT KEYFILE METHOD PATH [BODY_FILE] — Syncthing REST; the key goes in a header file, never argv.
st() {
  local port=$1 keyfile=$2 method=$3 path=$4 body=${5-} hdr
  hdr=$(mktemp "$RUN/hdr.XXXXXX")
  printf 'X-API-Key: %s\n' "$(tr -d '\r\n' <"$keyfile")" >"$hdr"
  local args=(-fsS -m 20 -X "$method" -H "@$hdr" "http://127.0.0.1:$port$path")
  [[ -n $body ]] && args+=(-H 'Content-Type: application/json' --data-binary "@$body")
  curl "${args[@]}" || {
    rm -f "$hdr"
    return 1
  }
  rm -f "$hdr"
}

secret_file() { # NAME
  local f="$STACK_DIR/secrets/$1"
  [[ -s $f ]] || (umask 077 && head -c 32 /dev/urandom | base64 -w0 | tr '+/' '-_' | tr -d '=' >"$f")
  chmod 600 "$f"
}

write_app_env() {
  local now_h start_h end_h
  now_h=$((10#$(date -u +%H)))
  start_h=$(((now_h + 12) % 24))
  end_h=$(((now_h + 13) % 24))
  cat >"$APP_ENV" <<EOF
# Generated by scripts/test-stack.sh — test stack only (no secrets in here).
NODE_ENV=production
LOG_LEVEL=info
TZ=UTC
PUBLIC_BASE_URL=http://127.0.0.1:$PUBLIC_PORT
ADMIN_BASE_URL=http://127.0.0.1:$ADMIN_PORT
PUBLIC_BIND=127.0.0.1
PUBLIC_PORT=$PUBLIC_PORT
ADMIN_BIND=127.0.0.1
ADMIN_PORT=$ADMIN_PORT
BT_PORT=$BT_PORT
WEBRTC_PORT=$WEBRTC_PORT
WEBRTC_ANNOUNCE_IP=
STUN_URLS=
DATA_DIR=$STACK_DIR/data
STATE_DIR=$STACK_DIR/state
SECRETS_DIR=$STACK_DIR/secrets
SYNCTHING_API_URL=http://127.0.0.1:$ST_SERVER_PORT
SYNCTHING_FOLDER_ID=$FOLDER_ID
SYNCTHING_PC_DEVICE_ID=
INGEST_QUIET_SECONDS=$QUIET
INGEST_RESCAN_SECONDS=5
CF_ACCESS_TEAM_DOMAIN=fileshare-test.invalid
CF_ACCESS_AUD=fileshare-test-aud
CF_ACCESS_CERTS_URL=http://127.0.0.1:$JWKS_PORT/cdn-cgi/access/certs
ADMIN_EMAILS=admin@fileshare-test.invalid
SNAPSHOT_DEBOUNCE_SECONDS=5
SNAPSHOT_PAUSE_WINDOW=$(printf '%02d:00-%02d:00' "$start_h" "$end_h")
TRUST_PROXY=false
EOF
}

write_compose_env() {
  cat >"$COMPOSE_ENV" <<EOF
STACK_DIR=$STACK_DIR
PUID=$(id -u)
PGID=$(id -g)
ST_SERVER_PORT=$ST_SERVER_PORT
ST_PC_PORT=$ST_PC_PORT
FILESHARE_TEST_IMAGE=$IMAGE
EOF
}

ensure_image() {
  if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
    IMAGE=fileshare-test:local
    info "building $IMAGE from the Dockerfile"
    docker build -q -t "$IMAGE" "$REPO_DIR" >/dev/null
  fi
}

st_json() { python3 -c "import json,sys; d=json.load(sys.stdin); print($1)"; }

start_real_syncthing() {
  local srv_key="$STACK_DIR/secrets/syncthing-api-key" pc_key="$STACK_DIR/secrets/syncthing-pc-api-key"
  local pc_id srv_id pc_ip i
  compose up -d --quiet-pull syncthing-server syncthing-pc >/dev/null
  wait_http "http://127.0.0.1:$ST_SERVER_PORT/rest/noauth/health" 90 || die "server Syncthing did not start"
  wait_http "http://127.0.0.1:$ST_PC_PORT/rest/noauth/health" 90 || die "pc Syncthing did not start"
  pc_id=$(st "$ST_PC_PORT" "$pc_key" GET /rest/system/status | st_json 'd["myID"]')
  srv_id=$(st "$ST_SERVER_PORT" "$srv_key" GET /rest/system/status | st_json 'd["myID"]')
  pc_ip=$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' "$PROJECT-syncthing-pc-1")

  # Server side: exactly what the operator runs in production.
  info "pairing with scripts/pair-pc.sh"
  APPDATA="$STACK_DIR" SYNCTHING_API_URL="http://127.0.0.1:$ST_SERVER_PORT" SYNCTHING_FOLDER_ID="$FOLDER_ID" \
    ENV_FILE="$APP_ENV" "$REPO_DIR/scripts/pair-pc.sh" --no-restart "$pc_id" "$pc_ip" >"$LOGS/pair-pc.log" 2>&1 ||
    die "pair-pc.sh failed (see $LOGS/pair-pc.log)"
  grep -q "^SYNCTHING_PC_DEVICE_ID=$pc_id\$" "$APP_ENV" || die "pair-pc.sh did not record the PC device ID"

  # PC side: what docs/pc-setup.md does on Windows.
  cat >"$RUN/pc-options.json" <<'EOF'
{"globalAnnounceEnabled": false, "localAnnounceEnabled": false, "relaysEnabled": false, "natEnabled": false,
 "urAccepted": -1, "urSeen": 3, "crashReportingEnabled": false, "autoUpgradeIntervalH": 0, "startBrowser": false}
EOF
  st "$ST_PC_PORT" "$pc_key" PATCH /rest/config/options "$RUN/pc-options.json" >/dev/null
  st "$ST_PC_PORT" "$pc_key" GET /rest/config/defaults/device |
    python3 -c 'import json,sys; d=json.load(sys.stdin); d.update(deviceID=sys.argv[1], name="server", addresses=["tcp://syncthing-server:22000"], autoAcceptFolders=False, paused=False); json.dump(d, open(sys.argv[2], "w"))' \
      "$srv_id" "$RUN/pc-device.json"
  st "$ST_PC_PORT" "$pc_key" PUT "/rest/config/devices/$srv_id" "$RUN/pc-device.json" >/dev/null
  st "$ST_PC_PORT" "$pc_key" GET /rest/config/defaults/folder |
    python3 -c '
import json, sys
f = json.load(sys.stdin)
f.update(id=sys.argv[1], label="fileshare outbox", path="/data/pc", type="sendreceive", fsWatcherEnabled=True, paused=False)
f["versioning"] = {"type": "", "params": {}}
f["devices"] = [{"deviceID": sys.argv[2], "introducedBy": "", "encryptionPassword": ""}]
json.dump(f, open(sys.argv[3], "w"))' "$FOLDER_ID" "$srv_id" "$RUN/pc-folder.json"
  st "$ST_PC_PORT" "$pc_key" PUT "/rest/config/folders/$FOLDER_ID" "$RUN/pc-folder.json" >/dev/null
  printf '%s' '{"ignore": ["(?d)desktop.ini", "(?d)Thumbs.db", "(?d).DS_Store", "(?d)~$*", "*.tmp"]}' >"$RUN/pc-ignores.json"
  for i in $(seq 1 20); do
    st "$ST_PC_PORT" "$pc_key" POST "/rest/db/ignores?folder=$FOLDER_ID" "$RUN/pc-ignores.json" >/dev/null 2>&1 && break
    sleep 0.5
  done

  info "waiting for the pc and server Syncthing to connect"
  for i in $(seq 1 120); do
    if st "$ST_SERVER_PORT" "$srv_key" GET /rest/system/connections 2>/dev/null |
      python3 -c 'import json,sys; c=json.load(sys.stdin)["connections"].get(sys.argv[1],{}); sys.exit(0 if c.get("connected") else 1)' "$pc_id"; then
      SERVER_DEVICE_ID=$srv_id
      PC_DEVICE_ID=$pc_id
      return 0
    fi
    sleep 0.5
  done
  die "Syncthing pc ↔ server did not connect"
}

start_fake_syncthing() {
  env_set_quiet SYNCTHING_PC_DEVICE_ID "FAKEPCD-AAAAAAA-BBBBBBB-CCCCCCC-DDDDDDD-EEEEEEE-FFFFFFF-GGGGGGG"
  start_bg fake-syncthing node test/stack/fake-syncthing.mjs "$ST_SERVER_PORT" "$STACK_DIR/secrets/syncthing-api-key" "$FOLDER_ID"
  wait_http "http://127.0.0.1:$ST_SERVER_PORT/rest/noauth/health" 20 || die "fake Syncthing did not start"
  SERVER_DEVICE_ID=""
  PC_DEVICE_ID=FAKEPCD-AAAAAAA-BBBBBBB-CCCCCCC-DDDDDDD-EEEEEEE-FFFFFFF-GGGGGGG
}

env_set_quiet() { ENV_FILE="$APP_ENV" env_set "$1" "$2" >/dev/null; }

write_stack_json() {
  python3 - "$STACK_DIR/stack.json" <<EOF
import json, sys
d = {
  "stackDir": "$STACK_DIR", "repoDir": "$REPO_DIR",
  "publicUrl": "http://127.0.0.1:$PUBLIC_PORT", "adminUrl": "http://127.0.0.1:$ADMIN_PORT",
  "ports": {"public": $PUBLIC_PORT, "admin": $ADMIN_PORT, "jwks": $JWKS_PORT, "bt": $BT_PORT, "webrtc": $WEBRTC_PORT,
            "syncthingServer": $ST_SERVER_PORT, "syncthingPc": $ST_PC_PORT},
  "paths": {"data": "$STACK_DIR/data", "outbox": "$STACK_DIR/data/outbox", "library": "$STACK_DIR/data/library",
            "state": "$STACK_DIR/state", "db": "$STACK_DIR/state/fileshare.db", "secrets": "$STACK_DIR/secrets",
            "pcFolder": "$STACK_DIR/pc-folder", "resticRepo": "$STACK_DIR/restic-repo", "logs": "$LOGS",
            "appLog": "$LOGS/app.log", "envFile": "$APP_ENV", "composeEnv": "$COMPOSE_ENV", "jwk": "$STACK_DIR/jwks-private.json"},
  "access": {"issuer": "https://fileshare-test.invalid", "audience": "fileshare-test-aud", "email": "admin@fileshare-test.invalid"},
  "syncthing": {"mode": "$SYNCTHING_MODE", "folderId": "$FOLDER_ID", "serverDeviceId": "$SERVER_DEVICE_ID", "pcDeviceId": "$PC_DEVICE_ID",
