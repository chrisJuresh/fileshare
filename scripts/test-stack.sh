  "compose": {"project": "$PROJECT", "file": "$COMPOSE_FILE_TEST", "envFile": "$COMPOSE_ENV", "image": "$IMAGE"},
  "ingestQuietSeconds": $QUIET, "restic": $RESTIC_ON,
