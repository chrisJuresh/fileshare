}

cmd_start() {
  SYNCTHING_MODE=real
  RESTIC_ON=True
  while [[ $# -gt 0 ]]; do
    case $1 in
      --syncthing)
        SYNCTHING_MODE=${2-}
        shift
        ;;
      --syncthing=*) SYNCTHING_MODE=${1#*=} ;;
      --no-restic) RESTIC_ON=False ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done
  [[ $SYNCTHING_MODE == real || $SYNCTHING_MODE == fake ]] || die "--syncthing real|fake"
  check_stack_dir
  pid_alive app && die "the test stack is already running (scripts/test-stack.sh stop)"
  [[ -f $REPO_DIR/dist/main.js ]] || die "run npm run build first"
  local p
  for p in "$PUBLIC_PORT" "$ADMIN_PORT" "$JWKS_PORT" "$BT_PORT" "$WEBRTC_PORT" "$ST_SERVER_PORT" "$ST_PC_PORT"; do
    port_free "$p" || die "port $p is in use"
  done

  mkdir -p "$SCRATCH"
  (umask 027 && mkdir -p "$STACK_DIR"/{data/outbox,data/library,data/staging,data/uploads,state,restic-repo,syncthing-server,syncthing-pc,pc-folder,tmp} "$RUN" "$LOGS")
  (umask 077 && mkdir -p "$STACK_DIR/secrets")
  chmod 700 "$STACK_DIR/secrets"
  for s in share-hmac-key syncthing-api-key syncthing-pc-api-key restic-password; do secret_file "$s"; done
  write_app_env
  write_compose_env

  if [[ $SYNCTHING_MODE == real || $RESTIC_ON == True ]]; then
    command -v docker >/dev/null || die "docker is required (or use --syncthing fake --no-restic)"
  fi
  [[ $RESTIC_ON == True ]] && ensure_image && write_compose_env
  if [[ $SYNCTHING_MODE == real ]]; then start_real_syncthing; else start_fake_syncthing; fi

  start_bg jwks node test/stack/jwks-server.mjs "$JWKS_PORT" "$STACK_DIR/jwks-private.json"
  wait_http "http://127.0.0.1:$JWKS_PORT/cdn-cgi/access/certs" 20 || die "JWKS server did not start"

  start_bg app node dist/main.js
  wait_http "http://127.0.0.1:$PUBLIC_PORT/healthz" 60 || die "app did not start (see $LOGS/app.log)"
  wait_http "http://127.0.0.1:$ADMIN_PORT/healthz" 10 || die "admin listener did not start"

  if [[ $RESTIC_ON == True ]]; then
    compose up -d restic >/dev/null
    info "restic runner started ($IMAGE, this checkout's dist/)"
  fi
  write_stack_json
  info "test stack is up ($STACK_DIR)"
  echo "  public  http://127.0.0.1:$PUBLIC_PORT"
  echo "  admin   http://127.0.0.1:$ADMIN_PORT   (Cf-Access-Jwt-Assertion signed with $STACK_DIR/jwks-private.json)"
  echo "  syncthing server http://127.0.0.1:$ST_SERVER_PORT  pc http://127.0.0.1:$ST_PC_PORT ($SYNCTHING_MODE)"
  echo "  logs    $LOGS   stack.json $STACK_DIR/stack.json"
}

cmd_stop() {
  local clean=false
  [[ ${1-} == --clean ]] && clean=true
  check_stack_dir
  stop_pid app
  stop_pid jwks
  stop_pid fake-syncthing
  if command -v docker >/dev/null && [[ -f $COMPOSE_ENV ]]; then
    compose down -v --remove-orphans -t 60 >/dev/null 2>&1 || true
    info "containers removed (project $PROJECT)"
  fi
  if $clean; then
    rm -rf "$STACK_DIR"
    info "removed $STACK_DIR"
  fi
}

cmd_restic() {
  [[ -f $COMPOSE_ENV ]] || die "stack not started"
  case ${1-} in
    start) compose up -d restic >/dev/null && info "restic runner started" ;;
    stop) compose stop -t 120 restic >/dev/null && compose rm -f restic >/dev/null && info "restic runner stopped" ;;
    *) die "usage: test-stack.sh restic start|stop" ;;
  esac
}

cmd_status() {
  local n
  for n in app jwks fake-syncthing; do
    if pid_alive "$n"; then echo "$n: running (pid $(cat "$RUN/$n.pid"))"; else echo "$n: stopped"; fi
  done
  [[ -f $COMPOSE_ENV ]] && compose ps --format '{{.Service}}: {{.State}} {{.Status}}' 2>/dev/null || true
}

case ${1-} in
  start)
    shift
    cmd_start "$@"
    ;;
  stop)
    shift
    cmd_stop "$@"
    ;;
  restic)
    shift
    cmd_restic "$@"
    ;;
  status) cmd_status ;;
  -h | --help | help) usage 0 ;;
  *) usage 1 ;;
esac
